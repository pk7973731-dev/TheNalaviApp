export function normalizeVillageInput(raw: string): string {
  return (raw || '').toLowerCase().replace(/[^a-z0-9]/g, '');
}

/**
 * Robust village match evaluator:
 * - Matches by numeric ID (1-20, "V01"-"V20", "கிராமம் 5", etc.)
 * - Matches by Tamil name or Tamil substring
 * - Matches by English name, normalizedName, or registered aliases
 * - Returns undefined if not matched. NEVER DEFAULTS TO VADAVALLI!
 */
export function findVillageMatch(input: string): VillageInfo | undefined {
  if (!input || !input.trim()) return undefined;
  const raw = input.trim();
  const lower = raw.toLowerCase();

  // 1. Direct Numeric ID Check (1 to 20, "01" to "20", "V01" to "V20", "v5", "village 5", "கிராமம் 5", "எண் 12")
  const idRegex = /(?:village|கிராமம்|எண்|கிராம\s*எண்|id|code|no\.?|v)?\s*#?([0-9]{1,2})\b/i;
  const idMatch = lower.match(idRegex);
  if (idMatch && idMatch[1]) {
    const num = parseInt(idMatch[1], 10);
    if (num >= 1 && num <= 20) {
      return COIMBATORE_VILLAGES.find((v) => v.id === num);
    }
  }

  // 2. Exact Tamil Name Match or Tamil Substring
  // (e.g. "தொண்டாமுத்தூர்", "பேரூர்", "குனியமுத்தூர்")
  const tamilExact = COIMBATORE_VILLAGES.find((v) => v.nameTa === raw);
  if (tamilExact) return tamilExact;

  const tamilSub = COIMBATORE_VILLAGES.find(
    (v) => raw.includes(v.nameTa) || (raw.length >= 4 && v.nameTa.includes(raw))
  );
  if (tamilSub) return tamilSub;

  // 3. English Name & Aliases Check
  const norm = normalizeVillageInput(raw);
  if (norm.length >= 3) {
    // Exact normalized name or exact alias
    const direct = COIMBATORE_VILLAGES.find(
      (v) =>
        v.normalizedName === norm ||
        v.name.toLowerCase() === lower ||
        (v.aliases && v.aliases.some((a) => normalizeVillageInput(a) === norm))
    );
    if (direct) return direct;

    // Substring match only with sufficient character length (>= 5) to avoid false matches
    if (norm.length >= 5) {
      const sub = COIMBATORE_VILLAGES.find(
        (v) =>
          norm.includes(v.normalizedName) ||
          v.normalizedName.includes(norm) ||
          (v.aliases &&
            v.aliases.some((a) => {
              const cleanA = normalizeVillageInput(a);
              return cleanA.length >= 5 && (norm.includes(cleanA) || cleanA.includes(norm));
            }))
      );
      if (sub) return sub;
    }
  }

  // Strictly return undefined if no exact or reliable match exists.
  return undefined;
}

export function isValidPilotVillage(villageInput: string): boolean {
  return !!findVillageMatch(villageInput);
}

/**
 * Helper to display all 20 village names with ID
 */
export function get20VillagesListText(lang: string = 'ta'): string {
  if (lang === 'ta') {
    const south = COIMBATORE_VILLAGES.filter((v) => v.id <= 15)
      .map((v) => `${v.id}. ${v.nameTa} (${v.name})`)
      .join('\n');
    const north = COIMBATORE_VILLAGES.filter((v) => v.id > 15)
      .map((v) => `${v.id}. ${v.nameTa} (${v.name})`)
      .join('\n');
    return `🏛️ கோவை தெற்கு வட்டம் (1-15):\n${south}\n\n🏛️ கோவை வடக்கு வட்டம் (16-20):\n${north}`;
  }

  const south = COIMBATORE_VILLAGES.filter((v) => v.id <= 15)
    .map((v) => `${v.id}. ${v.name} (${v.nameTa})`)
    .join('\n');
  const north = COIMBATORE_VILLAGES.filter((v) => v.id > 15)
    .map((v) => `${v.id}. ${v.name} (${v.nameTa})`)
    .join('\n');
  return `🏛️ Coimbatore South (1-15):\n${south}\n\n🏛️ Coimbatore North (16-20):\n${north}`;
}
